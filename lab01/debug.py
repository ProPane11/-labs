# Фрагмент А
# Причина ошибки: Переменные first и second содержат строки (тип str), поэтому оператор +
# выполняет конкатенацию (склеивание) "2" + "3" = "23".
# Ожидаемый результат: Сумма чисел 5. Для этого строки нужно преобразовать в целые числа (тип int).
# Типы данных: До преобразования — str, После преобразования — int.

first = "2"
second = "3"

print("Фрагмент А")
print(f"Тип first до преобразования: {type(first)}")
print(f"Тип second до преобразования: {type(second)}")

first = int(first)
second = int(second)

print(f"Тип first после преобразования: {type(first)}")
print(f"Тип second после преобразования: {type(second)}")

print(f"Результат: {first + second}")

# Фрагмент Б
# Причина ошибки: Функция input() всегда возвращает строку (тип str). Попытка сложить строку
# со значением 1 (тип int) вызывает ошибку TypeError.
# Ожидаемый результат: Число 18 (для ввода 17). Введенную строку необходимо преобразовать в целое
# число (тип int) перед сложением.
# Типы данных: До преобразования — str, После преобразования — int.

print()
print("Фрагмент Б")

age = input("Возраст: ")

print(f"Тип age до преобразования: {type(age)}")

age = int(age)

print(f"Тип age после преобразования: {type(age)}")
print(f"Возраст через год: {age + 1}")

# Фрагмент В
# Причина ошибки: Из-за приоритета операторов деление выполняется раньше сложения (сначала third / 3,
# затем результат прибавляется к first и second).
# Ожидаемый результат: Среднее арифметическое 7.0. Для корректного расчета сумму всех чисел нужно
# взять в круглые скобки.

print()
print("Фрагмент В")

first = 4
second = 7
third = 10

average = (first + second + third) / 3

print(f"Среднее значение: {average}")
